create or replace function public.set_row_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = timezone('utc'::text, now());
    return new;
end;
$$;

do $$
begin
    if to_regclass('public.calendar_events') is not null
       and not exists (select 1 from pg_trigger where tgname = 'set_calendar_events_updated_at') then
        create trigger set_calendar_events_updated_at
            before update on public.calendar_events
            for each row execute function public.set_row_updated_at();
    end if;

    if to_regclass('public.calendar_settings') is not null
       and not exists (select 1 from pg_trigger where tgname = 'set_calendar_settings_updated_at') then
        create trigger set_calendar_settings_updated_at
            before update on public.calendar_settings
            for each row execute function public.set_row_updated_at();
    end if;

    if to_regclass('public.whats_new') is not null
       and not exists (select 1 from pg_trigger where tgname = 'set_whats_new_updated_at') then
        create trigger set_whats_new_updated_at
            before update on public.whats_new
            for each row execute function public.set_row_updated_at();
    end if;

    if to_regclass('public.upcoming_events') is not null
