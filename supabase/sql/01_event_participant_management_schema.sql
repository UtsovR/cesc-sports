$$;

create or replace function public.validate_gallery_folder_hierarchy()
returns trigger
language plpgsql
as $$
declare
    parent_category_id bigint;
begin
    new.name = btrim(coalesce(new.name, ''));

    if new.name = '' then
        raise exception 'Folder name cannot be empty.';
    end if;

    if new.parent_folder_id is null then
        return new;
    end if;

    if new.id is not null and new.parent_folder_id = new.id then
        raise exception 'A folder cannot be its own parent.';
    end if;

    select category_id
    into parent_category_id
    from public.gallery_folders
    where id = new.parent_folder_id;

    if parent_category_id is null then
        raise exception 'Selected parent folder does not exist.';
    end if;

    if parent_category_id <> new.category_id then
        raise exception 'Parent folder must belong to the same gallery category.';
    end if;

    if new.id is not null and exists (
        with recursive parent_chain as (
            select id, parent_folder_id
            from public.gallery_folders
            where id = new.parent_folder_id

            union all

            select folder.id, folder.parent_folder_id
            from public.gallery_folders as folder
            inner join parent_chain on folder.id = parent_chain.parent_folder_id
        )
        select 1
        from parent_chain
        where id = new.id
    ) then
        raise exception 'A folder cannot be moved inside its own descendants.';
    end if;

    return new;
end;
$$;

create or replace function public.validate_gallery_image_folder_assignment()
returns trigger
language plpgsql
as $$
declare
    folder_category_id bigint;
begin
    if new.folder_id is null then
        return new;
    end if;

    select category_id
    into folder_category_id
    from public.gallery_folders
    where id = new.folder_id;

    if folder_category_id is null then
        raise exception 'Selected gallery folder does not exist.';
    end if;

    if folder_category_id <> new.category_id then
        raise exception 'Selected gallery folder must belong to the same category.';
    end if;

    return new;
end;
$$;

create or replace function public.prevent_deleting_nonempty_gallery_folder()
returns trigger
language plpgsql
as $$
begin
    if exists (
        select 1
        from public.gallery_folders
        where parent_folder_id = old.id
    ) or exists (
        select 1
        from public.gallery_images
        where folder_id = old.id
    ) then
        raise exception 'Cannot delete folder because it contains sub-folders or images.';
    end if;

    return old;
end;
$$;

