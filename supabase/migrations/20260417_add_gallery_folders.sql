create or replace function public.validate_gallery_image_folder_assignment()
returns trigger
language plpgsql
as $$
declare
    folder_category_id bigint;
begin
    if new.folder_id is null then
        return new;
    end if;

    select category_id
    into folder_category_id
    from public.gallery_folders
    where id = new.folder_id;

    if folder_category_id is null then
        raise exception 'Selected gallery folder does not exist.';
    end if;

    if folder_category_id <> new.category_id then
        raise exception 'Selected gallery folder must belong to the same category.';
    end if;

    return new;
end;
$$;

drop trigger if exists validate_gallery_image_folder_assignment on public.gallery_images;

create trigger validate_gallery_image_folder_assignment
    before insert or update on public.gallery_images
    for each row execute function public.validate_gallery_image_folder_assignment();

create or replace function public.prevent_deleting_nonempty_gallery_folder()
returns trigger
language plpgsql
as $$
begin
    if exists (
        select 1
        from public.gallery_folders
        where parent_folder_id = old.id
    ) or exists (
        select 1
        from public.gallery_images
        where folder_id = old.id
    ) then
        raise exception 'Cannot delete folder because it contains sub-folders or images.';
    end if;

    return old;
end;
$$;

drop trigger if exists prevent_deleting_nonempty_gallery_folder on public.gallery_folders;

create trigger prevent_deleting_nonempty_gallery_folder
    before delete on public.gallery_folders
    for each row execute function public.prevent_deleting_nonempty_gallery_folder();

