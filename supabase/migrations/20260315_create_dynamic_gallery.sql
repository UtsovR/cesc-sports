          and tablename = 'objects'
          and policyname = 'Authenticated users can upload gallery storage objects'
    ) then
        create policy "Authenticated users can upload gallery storage objects"
            on storage.objects
            for insert
            to authenticated
            with check (bucket_id = 'gallery-images');
    end if;
end
$$;

do $$
